// Helper to generate realistic historical candlestick data
function generateHistoricalCandles(basePrice: number, volatility: number, trend: number, days: number = 40): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice * (1 - (trend * days * 0.003));
  const now = Date.now();
  const dayMs = 24 * 60 * 60 * 1000;

  for (let i = days; i >= 0; i--) {
    const timestamp = now - i * dayMs;
    const dateObj = new Date(timestamp);
    const timeStr = `${dateObj.getMonth() + 1}/${dateObj.getDate()}`;
    
    // Simulate daily price moves with mean-reversion
    const dayMove = (Math.sin(i * 0.4) * 0.015 + (Math.random() - 0.48) * volatility + trend * 0.004) * currentPrice;
    const open = currentPrice;
    const close = Math.max(open + dayMove, currentPrice * 0.7);
    const high = Math.max(open, close) + Math.random() * volatility * currentPrice * 0.6;
    const low = Math.min(open, close) - Math.random() * volatility * currentPrice * 0.6;
    const volume = Math.floor(1000000 + Math.random() * 2500000 + (Math.abs(close - open) / currentPrice) * 5000000);
    
    // Contrarian sentiment oscillator: 
    // Usually inverted or leading (e.g. sharp drops create extreme fear)
    let sentiment = 50 + (close - basePrice) / (basePrice * 0.2) * 35 + (Math.random() - 0.5) * 15;
    sentiment = Math.max(8, Math.min(94, Math.round(sentiment)));

    const retailLongPct = Math.max(15, Math.min(92, Math.round(sentiment * 0.9 + (Math.random() - 0.5) * 10)));

    candles.push({
      time: timeStr,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
      sentiment,
      retailLongPct,
    });

    currentPrice = close;
  }
  return candles;
}

